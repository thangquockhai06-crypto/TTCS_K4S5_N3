export function getStoredUsers(): IUserItem[] {
  const raw = window.localStorage.getItem(USERS_STORAGE_KEY);
  if (!raw) {
    window.localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(INITIAL_USERS));
    return [...INITIAL_USERS];
  }
  try {
    const parsed = JSON.parse(raw) as IUserItem[];
    if (!Array.isArray(parsed) || parsed.length === 0) {
      window.localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(INITIAL_USERS));
      return [...INITIAL_USERS];
    }
    return parsed;
  } catch {
    window.localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(INITIAL_USERS));
    return [...INITIAL_USERS];
  }
}

export function saveStoredUsers(users: IUserItem[]): void {
  window.localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(users));
}

export function resetUsersToDefault(): IUserItem[] {
  window.localStorage.setItem(USERS_STORAGE_KEY, JSON.stringify(INITIAL_USERS));
  return [...INITIAL_USERS];
}
